def esc(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("\\", "\\\\").replace("'", "''")


def block(heading=None, paragraphs=None, items=None, children=None, highlight=False):
    return {
        "heading": heading,
        "paragraphs": paragraphs or [],
        "items": items or [],
        "children": children or [],
        "highlight": highlight,
    }


def scope(*blocks):
    return {"blocks": list(blocks)}


def ref(title, editors=None, edition=None, publisher=None, published_at=None, note=None):
    return {
        "title": title,
        "editors": editors,
        "edition": edition,
        "publisher": publisher,
        "publishedAt": published_at,
        "note": note,
    }


def headings_only(*titles: str):
    return scope(*(block(heading=t) for t in titles))


def prose_scope(text: str, highlight_heading=None, highlight_text=None):
    blocks = [block(paragraphs=[text])]
    if highlight_heading and highlight_text:
        blocks.append(block(heading=highlight_heading, paragraphs=[highlight_text], highlight=True))
    return scope(*blocks)


