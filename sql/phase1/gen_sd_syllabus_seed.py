def esc(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("\\", "\\\\").replace("'", "''")


def block(heading=None, paragraphs=None, items=None, children=None, highlight=False):
    return {
        "heading": heading,
        "paragraphs": paragraphs or [],
        "items": items or [],
        "children": children or [],
        "highlight": highlight,
    }


def scope(*blocks):
    return {"blocks": list(blocks)}


def ref(title, editors=None, edition=None, publisher=None, published_at=None, note=None):
    return {
        "title": title,
        "editors": editors,
        "edition": edition,
        "publisher": publisher,
        "publishedAt": published_at,
        "note": note,
    }


def work(seq, title, author_or_source=None):
    return {"seq": seq, "title": title, "authorOrSource": author_or_source}


def exam_form(types: list[str], score=100, minutes=120):
    return block(
        "II. 考试形式与题型范围",
        children=[
            block("一、考试形式", paragraphs=[f"闭卷、笔试。试卷满分 {score} 分，考试时间 {minutes} 分钟。"]),
            block("二、题型范围", items=types),
        ],
    )


ROWS: list[tuple] = []


def add(subject, scope_json, refs=None, works=None):
    ROWS.append(("山东", 2025, subject, scope_json, refs or [], works))


